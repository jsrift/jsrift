const traverse = ((_traverse as unknown as { default?: typeof _traverse }).default ??
  _traverse) as typeof _traverse;

/**
 * A rotation loop the recogniser solves as arithmetic is the one place a
 * slice's own initialisation outruns the interpreter's budget: every turn
 * decodes one string per checksum term, and an rc4 build with chained
 * wrappers takes hundreds of turns over a dozen terms. The native match is
 * confirmed by the interpreter run past the loop - its solution stood in
 * for it, the checksum's own terms among the sites compared - and only
 * when the loop body is the puzzle and nothing else.
 */

// ---------------------------------------------------------------------------
// Harness
// ---------------------------------------------------------------------------

function execute(code: string, timeout = 5_000): string {
  const trace: string[] = [];
  const timers: (() => void)[] = [];
  const log = (...args: unknown[]): void => {
    trace.push(args.map((value) => (typeof value === 'string' ? JSON.stringify(value) : String(value))).join(' '));
  };
  const queue = (fn: () => void): number => timers.push(fn);
  try {
    vm.runInNewContext(
      code,
      vm.createContext({ log, setTimeout: queue, setInterval: queue, clearInterval: () => undefined, clearTimeout: () => undefined }),
      { timeout },
    );
    for (let drained = 0; timers.length > 0 && drained < 32; drained++) timers.shift()!();
  } catch (error) {
    trace.push(`THROWN ${(error as Error).name}: ${(error as Error).message}`);
  }
  return trace.join('\n');
}

const PRESETS = ['conservative', 'balanced', 'aggressive'] as const;

function programPath(source: string): NodePath<t.Program> {
  const { ast } = parseSource(source);
  let found: NodePath<t.Program> | undefined;
  traverse(ast, {
    Program(path) {
      found = path;
      path.stop();
    },
  });
  if (!found) throw new Error('no Program path');
  found.scope.crawl();
  return found;
}

function build(
  source: string,
  roots: string[],
  options: Parameters<typeof resolveConfig>[0] = {},
  samples?: readonly (readonly (string | number)[])[],
) {
  const notes: { severity: Severity; message: string }[] = [];
  const decoder = buildDecoder(programPath(source), roots, resolveConfig(options), {
    reporter: { note: (severity, message) => notes.push({ severity, message }) },
    ...(samples ? { samples } : {}),
  });
  return { decoder, notes };
}

const CONFIRMED = /Confirmed the "(.+)" match for (\S+) by the interpreter on (\d+) of (\d+) call site\(s\) and on the (\d+) term\(s\) of the rotation checksum, run past the rotation loop with the (\d+) shift\(s\) it solves to/;

