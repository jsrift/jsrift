// The check spends one budget
// ---------------------------------------------------------------------------

describe('the check past the loop', () => {
  it('falls back to the whole slice, and its verdicts, when it cannot finish either', async () => {
    const source = rotating(TEMPLATE_LOOP);
    // A hundred steps decode nothing: the check is silent, the whole slice
    // runs out of budget in the loop the recogniser read, and the match
    // stands at balanced with the warning and is refused at conservative.
    const stood = build(source, ['_0xd', '_0xt'], { preset: 'balanced', sandbox: { maxSteps: 100 } });
    expect(stood.decoder?.tier).toBe('native');
    expect(stood.notes.some((note) => note.message.includes('stands unchecked'))).toBe(true);
    expect(stood.notes.some((note) => CONFIRMED.test(note.message))).toBe(false);
    const refused = build(source, ['_0xd', '_0xt'], { preset: 'conservative', sandbox: { maxSteps: 100 } });
    expect(refused.decoder).toBeUndefined();
    expect(refused.notes.some((note) => note.message.includes('conservative preset inlines only what is proved'))).toBe(true);
  });

  it('cuts the spread to what the budget affords past the head, and always compares the checksum terms', () => {
    // Three hundred and four distinct sites over forty entries, a plain
    // lookup a handful of steps each: the head of thirty-two measures a
    // call, and the rest is spread over what is left of a thousand steps.
    // The two terms of the checksum are compared whatever the budget, and
    // are not sites of the program at all.
    const sites: (readonly (string | number)[])[] = [];
    for (let k = 0; k < 8; k++) for (let i = 2; i < 40; i++) sites.push([i, k]);
    const uses = sites.map(([i, k]) => `_0xd(${i}, ${k})`).join(', ');
    const source = `
      var _0xt = [${ENTRIES}];
      (function (_0xp, _0xq) {
        var _0xr = _0xd;
        ${TEMPLATE_LOOP}
      }(_0xt, 500));
      function _0xd(_0xi, _0xk) { return _0xt[_0xi]; }
      log(${uses});
    `;
    const distinct = new Set(sites.map((s) => s.join(','))).size;
    const tight = build(source, ['_0xd', '_0xt'], { preset: 'balanced', sandbox: { maxSteps: 1_000 } }, sites);
    expect(tight.decoder?.tier).toBe('native');
    const tightLine = tight.notes.map((n) => n.message).find((m) => CONFIRMED.test(m))!;
    expect(tightLine, tight.notes.map((n) => n.message).join('\n')).toBeDefined();
    const [, , , checked, of, terms] = CONFIRMED.exec(tightLine)!;
    expect(Number(of)).toBe(distinct);
    expect(Number(checked)).toBeGreaterThanOrEqual(32);
    expect(Number(checked)).toBeLessThan(distinct);
    expect(Number(terms)).toBe(2);

    const wide = build(source, ['_0xd', '_0xt'], { preset: 'balanced' }, sites);
    const wideLine = wide.notes.map((n) => n.message).find((m) => CONFIRMED.test(m))!;
    expect(Number(CONFIRMED.exec(wideLine)![3])).toBe(distinct);
  });
});
